String texto(String idioma, String clave) =>
    textosPanel[idioma]?[clave] ?? textosPanel[idiomaPorDefecto]![clave] ?? clave;

// Fecha y hora en el formato del idioma, p. ej. "10 nov 2026, 22:07" o "10. Nov. 2026, 22:07"
String fechaLegible(DateTime f, String idioma) {
  final meses = texto(idioma, 'meses').split(',');
  String d(int n) => n.toString().padLeft(2, '0');
  return texto(idioma, 'formatoFecha')
      .replaceAll('{d}', '${f.day}')
      .replaceAll('{m}', meses[f.month - 1])
      .replaceAll('{a}', '${f.year}')
      .replaceAll('{h}', '${d(f.hour)}:${d(f.minute)}');
}

// "Hace 5 min", "Ayer", "Hace 3 días"... o null si pasó más de una semana (entonces se muestra la fecha)
String? fechaRelativa(DateTime f, DateTime ahora, String idioma) {
  final diferencia = ahora.difference(f);
  if (diferencia.isNegative || diferencia.inDays >= 7) return null;
  String con(String clave, int n) => texto(idioma, clave).replaceAll('{n}', '$n');
  if (diferencia.inMinutes < 1) return texto(idioma, 'haceMomento');
  if (diferencia.inHours < 1) return con('haceMinutos', diferencia.inMinutes);
  if (diferencia.inDays < 1) return con('haceHoras', diferencia.inHours);
  if (diferencia.inDays == 1) return texto(idioma, 'ayer');
  return con('haceDias', diferencia.inDays);
}
